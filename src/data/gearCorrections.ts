import { db, type HikingDB } from './db'
import { parseGearDescription } from '../domain/gearDescription'

/** Moves historical Excel weights out of the manufacturer's field.
 * Only original spreadsheet records are eligible; user's own edits and
 * properly sourced manufacturer measurements are not replaced. */
export async function correctImportedGearFields(database: HikingDB = db): Promise<number> {
  return database.transaction('rw', [database.gear,database.sources], async () => {
    const sources = new Set((await database.sources.toArray())
      .filter(s => s.provider === 'Пользовательский файл' && /Крым|Архыз/.test(String(s.title ?? '')))
      .map(s => s.id))
    let count = 0
    for (const row of await database.gear.toArray()) {
      if (!sources.has(String(row.sourceRef ?? ''))) continue
      const patch: Record<string,string|number|null>={}
      if (typeof row.manufacturerWeightG === 'number' && row.listedWeightG == null) {
        patch.listedWeightG = row.manufacturerWeightG
        patch.manufacturerWeightG = null
      }
      const oldDescription = String(row.sourceDescription || row.model || '')
      const parsed = parseGearDescription(oldDescription,row.name)
      const firstWord = String(row.model ?? '').trim().split(/[\s,]/)[0]
      if (parsed.brand && (!row.brand || row.brand === firstWord)) patch.brand=parsed.brand
      if (!row.sourceDescription && oldDescription) patch.sourceDescription=oldDescription
      if (row.model === oldDescription && parsed.model !== oldDescription) patch.model=parsed.model
      for (const field of ['lengthCm','widthCm','thicknessCm','rValue'] as const) {
        if (row[field] == null && parsed[field] !== null) patch[field] = parsed[field]
      }
      if (!row.temperatureHint && parsed.temperatureHint) patch.temperatureHint=parsed.temperatureHint
      if (!row.specifications && parsed.specifications) patch.specifications=parsed.specifications
      if (Object.keys(patch).length) {
        patch.updatedAt = new Date().toISOString()
        await database.gear.update(row.id,patch)
        count++
      }
    }
    return count
  })
}

/** Repair clearly identifiable Jetboil brand names in previously imported entries.
 * A verified manufacturer name is distinct from verifying the item's exact SKU or weight. */
export async function correctJetboilBrand(database: HikingDB = db): Promise<number> {
  return database.transaction('rw', database.gear, async () => {
    let changed = 0
    for (const row of await database.gear.toArray()) {
      if (String(row.brand ?? '').trim()) continue
      const name = String(row.name ?? '')
      const model = String(row.model ?? '')
      if (!/(^|[\s,(])jetboil\b/i.test(model) && !/^jetboil\b/i.test(name)) continue
      await database.gear.update(row.id, {brand:'Jetboil',updatedAt:new Date().toISOString()})
      changed++
    }
    return changed
  })
}


/** The source lists are the user's own equipment, as explicitly confirmed.
 * Two generated rows for the same catalog item in different trip workbooks
 * represent re-use, not two separate purchases. Never merge user-edited rows.
 */
export async function confirmSpreadsheetGearOwnership(database: HikingDB = db): Promise<number> {
  return database.transaction('rw', [database.ownedGear,database.gear,database.sources], async () => {
    const owned = await database.ownedGear.toArray()
    const sourceIds=new Set((await database.sources.toArray())
      .filter(s => s.provider === 'Пользовательский файл' && /Крым|Архыз/.test(String(s.title ?? '')))
      .map(s=>s.id))
    const gear=(await database.gear.toArray()).filter(x=>sourceIds.has(String(x.sourceRef || '')))
    const byGear=new Map<string,typeof owned>()
    for (const row of owned) {
      const k=String(row.catalogItemId)
      byGear.set(k,[...(byGear.get(k) ?? []),row])
    }
    let changes=0
    for(const item of gear) {
      const personal=byGear.get(item.id)||[]
      if(!personal.length) {
        const now=new Date().toISOString()
        await database.ownedGear.add({id:crypto.randomUUID(),createdAt:now,updatedAt:now,
          catalogItemId:item.id,nickname:String(item.model || item.name),quantityOwned:1,
          measuredWeightG:null,ownershipStatus:'confirmed',notes:''})
        changes++
        continue
      }
      const autogenerated=personal.filter(row => / — (?:Архыз|Крым) 4 дня$/.test(String(row.nickname ?? '')))
      const keep=autogenerated[0]
      for(const row of personal) {
        const patch:Record<string,string|number|null>={}
        if(row.ownershipStatus !== 'confirmed')patch.ownershipStatus='confirmed'
        if(/ — (?:Архыз|Крым) 4 дня$/.test(String(row.nickname ?? '')))
          patch.nickname=String(item.model || item.name)
        // The Excel value was a carried/listed weight, not a separate physical measurement.
        if (autogenerated.includes(row) && typeof row.measuredWeightG==='number' &&
          row.measuredWeightG === item.listedWeightG) patch.measuredWeightG=null
        if(Object.keys(patch).length) {
          patch.updatedAt=new Date().toISOString()
          await database.ownedGear.update(row.id,patch)
          Object.assign(row,patch)
          changes++
        }
      }
      if(keep && autogenerated.length>1) {
        for(const row of autogenerated.slice(1)) {
          // Only collapse untouched generated placeholders. Preserve distinct measured or annotated items.
          if(String(row.notes || '').trim() || (row.measuredWeightG !== null && row.measuredWeightG !== undefined)) continue
          if(Number(row.quantityOwned)!==1)continue
          await database.ownedGear.delete(row.id)
          changes++
        }
      }
    }
    return changes
  })
}
