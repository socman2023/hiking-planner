import { expect, test } from '@playwright/test'

test('создать продукт, фасовку и сохранить карточки в личной библиотеке', async ({ page }) => {
  await page.goto('/library')
  await expect(page.getByRole('heading', { name: 'Моя библиотека' })).toBeVisible()
  await page.getByRole('button', { name: 'Добавить продукт' }).click()
  await page.getByLabel('Название', { exact: true }).fill('Сухари ржаные')
  await page.getByLabel('Ккал / 100 г').fill('310')
  await page.getByRole('dialog').getByRole('button', { name: 'Сохранить' }).click()
  await expect(page.getByText('Сухари ржаные').first()).toBeVisible()
  await page.getByRole('button', { name: /Сухари ржаные/ }).click()
  await page.getByRole('button', { name: 'Добавить', exact: true }).click()
  await page.getByLabel('Название фасовки').fill('Пакет 120 г')
  await page.getByLabel('Масса продукта, г').fill('120')
  await page.getByRole('dialog').getByRole('button', { name: 'Сохранить' }).click()
  await expect(page.getByText('Пакет 120 г')).toBeVisible()
  await page.reload()
  await expect(page.getByText('Сухари ржаные')).toBeVisible()
})
test('создать медицинское изделие и конкретную упаковку', async ({ page }) => {
  await page.goto('/library')
  await page.getByRole('tab', { name: /Аптечный каталог/ }).click()
  await page.getByRole('button', { name: 'Добавить позицию' }).click()
  await page.getByLabel('Тип', { exact: true }).selectOption('device')
  await page.getByLabel('Название', { exact: true }).fill('Стерильный бинт')
  await page.getByRole('dialog').getByRole('button', { name: 'Сохранить' }).click()
  await page.getByRole('button', { name: /Стерильный бинт/ }).click()
  await page.getByRole('button', { name: 'Добавить', exact: true }).click()
  await page.getByLabel('Название упаковки').fill('Домашняя упаковка')
  await page.getByLabel('Годен до').fill('2028-12-01')
  await page.getByRole('dialog').getByRole('button', { name: 'Сохранить' }).click()
  await expect(page.getByText('Срок годности: 2028-12-01')).toBeVisible()
})
