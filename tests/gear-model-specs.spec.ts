import { expect, test } from '@playwright/test'

test('the actual UberLite source separates brand, model, specifications and confirms owned quantity', async ({page}) => {
  await page.goto('/library')
  await expect(page.locator('.library-seed-banner small')).toContainText(/LighterPack:/, {timeout:30000})
  await page.getByRole('tab',{name:/Снаряжение/}).click()
  await page.getByLabel('Поиск в библиотеке').fill('NeoAir Uberlite')
  await expect(page.locator('.library-entry')).toHaveCount(1)
  await page.locator('.library-entry').click()
  const card = page.locator('.library-detail')
  const value = (label:string) => card.locator('.library-attributes > div')
    .filter({has:page.locator('dt', {hasText:label})}).locator('dd')
  await expect(value('Бренд')).toHaveText('Therm-A-Rest')
  await expect(value('Модель')).toHaveText('NeoAir Uberlite')
  await expect(value('Длина, см')).toHaveText('183')
  await expect(value('Ширина, см')).toHaveText('51')
  await expect(value('Толщина, см')).toHaveText('6.4')
  await expect(value('R-Value')).toHaveText('2')
  await expect(value('Температурный ориентир')).toHaveText('до 0')
  await expect(card.getByText('В наличии: 1 шт.')).toBeVisible()
  await expect(card).not.toContainText('Наличие не подтверждено')
  await page.reload()
  await expect(page.locator('.library-seed-banner small')).toContainText(/LighterPack:/,{timeout:30000})
  await page.getByRole('tab',{name:/Снаряжение/}).click()
  await page.getByLabel('Поиск в библиотеке').fill('NeoAir Uberlite')
  await expect(page.locator('.library-entry')).toHaveCount(1)
})
