import { expect, test } from '@playwright/test'

test('создать, редактировать и копировать одиночный поход', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Новый поход' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByPlaceholder('Например, Карельские озёра').fill('Поход к озёрам')
  await dialog.getByPlaceholder('Карелия, Хибины, Кавказ…').fill('Карелия')
  await dialog.getByLabel('Дата начала').fill('2027-07-12')
  await dialog.getByLabel('Продолжительность').fill('3')
  await dialog.getByRole('button', { name: 'Создать поход' }).click()
  await expect(page.getByRole('heading', { name: 'Поход к озёрам' })).toBeVisible()
  await expect(page.locator('.day-row')).toHaveCount(3)
  await page.getByRole('button', { name: 'Изменить день 2' }).click()
  await page.getByRole('dialog').getByPlaceholder('Например, Подъём к озеру').fill('Выход к перевалу')
  await page.getByRole('dialog').getByRole('button', { name: 'Сохранить' }).click()
  await expect(page.getByText('Выход к перевалу')).toBeVisible()
  await page.getByRole('button', { name: 'Изменить', exact: true }).click()
  await page.getByRole('dialog').getByLabel('Продолжительность').fill('5')
  await page.getByRole('dialog').getByRole('button', { name: 'Сохранить изменения' }).click()
  await expect(page.locator('.day-row')).toHaveCount(5)
  await expect(page.getByText('Выход к перевалу')).toBeVisible()
  await page.getByRole('button', { name: 'Копировать' }).click()
  await expect(page.getByRole('heading', { name: 'Поход к озёрам — копия' })).toBeVisible()
  await expect(page.locator('.day-row')).toHaveCount(5)
})

test('резервная копия восстанавливает походы', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Новый поход' }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByPlaceholder('Например, Карельские озёра').fill('Мой тест')
  await dialog.getByRole('button', { name: 'Создать поход' }).click()
  await page.goto('/settings')
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Скачать JSON' }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toMatch(/^hiking-planner-backup-/)
  const fs = await import('node:fs/promises')
  const stream = await download.createReadStream()
  const chunks: Buffer[] = []
  for await (const chunk of stream) chunks.push(Buffer.from(chunk))
  const backup = Buffer.concat(chunks)
  await page.locator('input[type="file"]').setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: backup })
  await expect(page.getByText('Файл прошёл проверку')).toBeVisible()
  page.once('dialog', async dialog => { await dialog.accept() })
  await page.getByRole('button', { name: 'Заменить данные содержимым файла' }).click()
  await expect(page.getByRole('heading', { name: 'Мои походы' })).toBeVisible()
  await expect(page.getByText('Мой тест')).toBeVisible({ timeout: 15000 })
  expect(fs).toBeDefined()
})
